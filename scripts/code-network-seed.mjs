// Builds convex/codeNetwork/seed.ts, the demo network of this repository, from the checked-out code and the
// plain-language labels in scripts/code-network/turtl-labels.json. Run from the repository root: node scripts/code-network-seed.mjs
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { buildGraph, fillClusters } from "../convex/codeNetwork/graph.ts";

const OUTPUT = "convex/codeNetwork/seed.ts";
const repo = "ronoktanvir/turtl";
const ref = execSync("git rev-parse HEAD", { encoding: "utf8" }).trim();
const files = execSync("git ls-files --cached --others --exclude-standard", { encoding: "utf8" })
  .trim()
  .split("\n")
  .filter((path) => path !== OUTPUT && /\.(ts|tsx|js|jsx|mjs)$/.test(path))
  .map((path) => ({ path, content: readFileSync(path, "utf8") }));
const { nodes: graphNodes, edges } = buildGraph(files);
const labels = JSON.parse(readFileSync("scripts/code-network/turtl-labels.json", "utf8"));
const clusterIds = new Set(labels.clusters.map((cluster) => cluster.id));
const assigned = new Map(
  Object.entries(labels.nodes).filter(([, label]) => clusterIds.has(label.clusterId)).map(([id, label]) => [id, label.clusterId]),
);
const clusterOf = fillClusters(graphNodes, edges, assigned, labels.clusters[0].id);
const unlabelled = graphNodes.filter((node) => !labels.nodes[node.id]).map((node) => node.id);
const nodes = graphNodes.map((node) => ({
  id: node.id,
  clusterId: clusterOf.get(node.id),
  label: labels.nodes[node.id]?.label ?? node.label,
  kind: node.kind,
  ...(node.path ? { path: node.path } : {}),
  summary: labels.nodes[node.id]?.summary ?? "",
  weight: node.weight,
}));
const clusters = labels.clusters.filter((cluster) => nodes.some((node) => node.clusterId === cluster.id));
const network = { repo, ref, generatedAt: Date.now(), clusters, nodes, edges };
writeFileSync(
  OUTPUT,
  `// @generated by scripts/code-network-seed.mjs from ${repo} at ${ref}. Do not edit; run the script again.
import type { NetCluster, NetEdge, NetNode } from "./schema";

export const SEED_NETWORK: {
  repo: string;
  ref: string;
  generatedAt: number;
  clusters: NetCluster[];
  nodes: NetNode[];
  edges: NetEdge[];
} = ${JSON.stringify(network, null, 2)};
`,
);
console.log(`${clusters.length} clusters, ${nodes.length} nodes, ${edges.length} edges at ${ref.slice(0, 7)}`);
if (unlabelled.length) console.log(`Without a plain label (summary left empty): ${unlabelled.join(", ")}`);
